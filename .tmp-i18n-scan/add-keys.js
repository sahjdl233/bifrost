// The locale files indent nesting with 2 tabs but leaf keys with 8 spaces.
function render(obj, depth) {
	const pad = "\t".repeat(depth);
	const inner = "\t".repeat(depth + 1);
	const out = [];
	const entries = Object.entries(obj);
	entries.forEach(([k, v], idx) => {
		const comma = idx < entries.length - 1 ? "," : "";
		if (typeof v === "object" && v !== null) {
			out.push(`${pad}${JSON.stringify(k)}: {`);
			out.push(...render(v, depth + 1).map((l) => inner + l));
			out.push(`${pad}}${comma}`);
		} else {
			out.push(`${pad}${JSON.stringify(k)}: ${JSON.stringify(v)}${comma}`);
		}
	});
	return out;
}

for (const [lang, file] of [
	["en", "ui/lib/locales/en.json"],
	["zh", "ui/lib/locales/zh-CN.json"],
]) {
	const src = fs.readFileSync(file, "utf8");
	const lines = src.split("\n");
	const blockStart = lines.findIndex((l) => /routingRules/.test(l) && /:\s*\{\s*$/.test(l));
	if (blockStart < 0) throw new Error("routingRules block not found in " + file);
	// The block currently ends with providerModelHeadersParamsLimits; append after it.
	const lastKey = lines.findIndex((l, i) => i > blockStart && /"providerModelHeadersParamsLimits"/.test(l));
	if (lastKey < 0) throw new Error("anchor key not found in " + file);
	lines[lastKey] = lines[lastKey] + ",";
	const rendered = render(additions[lang], 2).map((l) => (l.startsWith("\t") ? "        " + l.slice(2) : l));
	lines.splice(lastKey + 1, 0, ...rendered.map((l) => l));
	fs.writeFileSync(file, lines.join("\n"));
	console.log(file + ": inserted " + rendered.length + " lines after line " + (lastKey + 1));
}
